import { chromium } from 'playwright';
const b = await chromium.launch();
const PASS = 'dbg' + Math.random().toString(36).slice(2, 12);
const mk = async () => { const p = await (await b.newContext({ locale: 'zh-CN' })).newPage(); p.on('console', (m) => console.log('C', m.text())); p.on('pageerror', (e) => console.log('ERR', e.message)); await p.goto(`http://127.0.0.1:8099/#${PASS}`); await p.waitForSelector('#sendButton:not([disabled])'); return p; };
const A = await mk(), B = await mk();
await A.waitForFunction(() => !document.getElementById('trStart').disabled);
await A.click('#trStart');
await B.waitForFunction(() => !document.getElementById('gamePanel').hidden);
await A.waitForTimeout(1500);
console.log('A form hidden', await A.locator('#trForm').isHidden(), await A.locator('#gameLine').innerText());
await A.fill('#trNote', 'hello note');
await A.click('#trSend');
await A.waitForTimeout(4000);
console.log('A:', (await A.locator('#messages').innerText()).slice(-300));
console.log('B:', (await B.locator('#messages').innerText()).slice(-300));
await A.click('#gameVotes .pact-betray');
await B.click('#gameVotes .pact-keep');
await A.waitForTimeout(6000);
console.log('B:', (await B.locator('#messages').innerText()).slice(-300));
console.log('B line', await B.locator('#gameLine').innerText());
await b.close();
